local test = require('test_helper')

local sum_arguments = test.load_function()
local total, count = sum_arguments(1, nil, 3, nil)
test.equal(4, total)
test.equal(4, count)
total, count = sum_arguments()
test.equal(0, total)
test.equal(0, count)
total, count = sum_arguments(nil, nil)
test.equal(0, total)
test.equal(2, count)
total, count = sum_arguments(-2, 0, 5)
test.equal(3, total)
test.equal(3, count)
total, count = sum_arguments(nil, 2, nil, 3, nil)
test.equal(5, total)
test.equal(5, count)
