local test = require('test_helper')

local list_info = test.load_function()
local count, first, last = list_info({ 'red', 'green', 'blue' })
test.equal(3, count)
test.equal('red', first)
test.equal('blue', last)
count, first, last = list_info({})
test.equal(0, count)
test.equal(nil, first)
test.equal(nil, last)
count, first, last = list_info({ false })
test.equal(1, count)
test.equal(false, first)
test.equal(false, last)
