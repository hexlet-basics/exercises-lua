local test = require('test_helper')

local count_doublings = test.load_function()
local value, steps = count_doublings(20)
test.equal(32, value)
test.equal(5, steps)
value, steps = count_doublings(1)
test.equal(1, value)
test.equal(0, steps)
value, steps = count_doublings(8)
test.equal(8, value)
test.equal(3, steps)
value, steps = count_doublings(2)
test.equal(2, value)
test.equal(1, steps)
value, steps = count_doublings(1000000)
test.equal(1048576, value)
test.equal(20, steps)
