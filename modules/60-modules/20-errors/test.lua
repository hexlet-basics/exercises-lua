local test = require('test_helper')

local safe_call = test.load_function()
local value, message = safe_call(function(number) return number * 2 end, 4)
test.equal(8, value)
test.equal(nil, message)
value, message = safe_call(function() error('bad input', 0) end, 0)
test.equal(nil, value)
test.equal('bad input', message)
value, message = safe_call(function() return false end, 0)
test.equal(false, value)
test.equal(nil, message)
value, message = safe_call(function() return nil end, 0)
test.equal(nil, value)
test.equal(nil, message)
local object = {}
value, message = safe_call(function() error(object) end, 0)
test.equal(nil, value)
test.equal(object, message)
